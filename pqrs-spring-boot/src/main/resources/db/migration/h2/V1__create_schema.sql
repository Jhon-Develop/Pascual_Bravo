CREATE TABLE citizens (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    document VARCHAR(30) NOT NULL,
    name VARCHAR(120) NOT NULL,
    email VARCHAR(150),
    phone VARCHAR(30),
    CONSTRAINT pk_citizens PRIMARY KEY (id),
    CONSTRAINT uk_citizens_document UNIQUE (document)
);

CREATE TABLE responsibles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    document VARCHAR(30) NOT NULL,
    name VARCHAR(120) NOT NULL,
    email VARCHAR(150),
    area VARCHAR(100) NOT NULL,
    role VARCHAR(20) NOT NULL,
    CONSTRAINT pk_responsibles PRIMARY KEY (id),
    CONSTRAINT uk_responsibles_document UNIQUE (document)
);

CREATE TABLE answers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    content VARCHAR(5000) NOT NULL,
    answer_date DATE NOT NULL,
    author_id BIGINT NOT NULL,
    CONSTRAINT pk_answers PRIMARY KEY (id),
    CONSTRAINT fk_answers_author FOREIGN KEY (author_id) REFERENCES responsibles(id)
);

CREATE TABLE pqrs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    reference VARCHAR(30),
    type VARCHAR(20) NOT NULL,
    description VARCHAR(5000) NOT NULL,
    state VARCHAR(20) NOT NULL,
    created_date DATE NOT NULL,
    limited_date DATE NOT NULL,
    citizen_id BIGINT NOT NULL,
    responsible_id BIGINT,
    answer_id BIGINT,
    CONSTRAINT pk_pqrs PRIMARY KEY (id),
    CONSTRAINT uk_pqrs_reference UNIQUE (reference),
    CONSTRAINT uk_pqrs_answer UNIQUE (answer_id),
    CONSTRAINT fk_pqrs_citizen FOREIGN KEY (citizen_id) REFERENCES citizens(id),
    CONSTRAINT fk_pqrs_responsible FOREIGN KEY (responsible_id) REFERENCES responsibles(id),
    CONSTRAINT fk_pqrs_answer FOREIGN KEY (answer_id) REFERENCES answers(id)
);

CREATE INDEX idx_pqrs_state_limited_date ON pqrs(state, limited_date);
CREATE INDEX idx_pqrs_citizen ON pqrs(citizen_id);
CREATE INDEX idx_pqrs_responsible ON pqrs(responsible_id);
